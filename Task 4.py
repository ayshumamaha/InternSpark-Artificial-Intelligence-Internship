# Automatically install LIME if it is missing
try:
    from lime.lime_tabular import LimeTabularExplainer
except ImportError:
    print("Installing LIME...")
    subprocess.check_call([
        sys.executable, "-m", "pip", "install", "lime"
    ])
    from lime.lime_tabular import LimeTabularExplainer

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score, precision_score,
    recall_score, f1_score
)
from sklearn.inspection import permutation_importance

# 1. Generate demonstration dataset
print("Creating Responsible AI Dataset...")

np.random.seed(42)

n = 1200

# Synthetic group attribute:
# 0 = Group A, 1 = Group B
group = np.random.randint(0, 2, n)

ability = np.random.normal(0, 1, n)

# A proxy feature correlated with group
proxy_signal = (
    ability + 1.0 * group + np.random.normal(0, 0.5, n)
)

income_score = (
    ability + np.random.normal(0, 0.5, n)
)

experience = (
    5 + 2 * ability + np.random.normal(0, 1, n)
)

# Target labels
target_score = (
    ability + 0.8 * group + np.random.normal(0, 0.8, n)
)

y = (target_score > np.median(target_score)).astype(int)

# Sensitive group attribute is kept separate
X = pd.DataFrame({
    "Income_Score": income_score,
    "Experience": experience,
    "Proxy_Signal": proxy_signal
})

print("Dataset Shape:", X.shape)

# 2. Split dataset
X_train, X_test, y_train, y_test, group_train, group_test = (
    train_test_split(
        X, y, group,
        test_size=0.2,
        random_state=42,
        stratify=y
    )
)

# 3. Train model
print("\nTraining Classification Model...")

model = RandomForestClassifier(
    n_estimators=100,
    random_state=42
)

model.fit(X_train, y_train)

predictions = model.predict(X_test)

# 4. Overall evaluation
print("\nOVERALL MODEL PERFORMANCE")

print("Accuracy:", round(
    accuracy_score(y_test, predictions), 4
))

print("Precision:", round(
    precision_score(y_test, predictions), 4
))

print("Recall:", round(
    recall_score(y_test, predictions), 4
))

print("F1 Score:", round(
    f1_score(y_test, predictions), 4
))

# 5. Feature importance
importance = permutation_importance(
    model,
    X_test,
    y_test,
    n_repeats=5,
    random_state=42
)

importance_df = pd.DataFrame({
    "Feature": X.columns,
    "Importance": importance.importances_mean
}).sort_values(by="Importance", ascending=False)

print("\nFEATURE IMPORTANCE")
print(importance_df)

plt.figure(figsize=(8, 5))

plt.bar(
    importance_df["Feature"],
    importance_df["Importance"]
)

plt.title("Feature Importance")
plt.xlabel("Features")
plt.ylabel("Importance")
plt.tight_layout()
plt.show()

# 6. LIME local explanation
print("\nGENERATING LIME EXPLANATION")

explainer = LimeTabularExplainer(
    training_data=X_train.to_numpy(),
    feature_names=list(X.columns),
    class_names=["Class 0", "Class 1"],
    mode="classification",
    random_state=42
)

explanation = explainer.explain_instance(
    X_test.iloc[0].to_numpy(),
    model.predict_proba,
    num_features=3
)

print("\nLocal Explanation:")
for feature, contribution in explanation.as_list():
    print(feature, ":", round(contribution, 4))

fig = explanation.as_pyplot_figure()
plt.title("LIME Local Explanation")
plt.tight_layout()
plt.show()

# 7. Fairness analysis
print("\nFAIRNESS ANALYSIS")

fairness_results = []

for group_value in [0, 1]:

    mask = group_test == group_value

    actual = y_test[mask]
    predicted = predictions[mask]

    accuracy = accuracy_score(actual, predicted)
    precision = precision_score(
        actual, predicted, zero_division=0
    )
    recall = recall_score(
        actual, predicted, zero_division=0
    )

    selection_rate = predicted.mean()

    fairness_results.append({
        "Group": f"Group {group_value}",
        "Samples": int(mask.sum()),
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "Selection Rate": selection_rate
    })

fairness_df = pd.DataFrame(fairness_results)

print(fairness_df.round(4))

# 8. Compare group metrics
fairness_df.set_index("Group")[
    ["Accuracy", "Precision", "Recall", "Selection Rate"]
].plot(kind="bar", figsize=(10, 6))

plt.title("Fairness Comparison Across Groups")
plt.ylabel("Score")
plt.ylim(0, 1.05)
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

# 9. Calculate selection rate difference
selection_rates = fairness_df["Selection Rate"].values

difference = abs(
    selection_rates[0] - selection_rates[1]
)

print("\nSELECTION RATE DIFFERENCE:", round(difference, 4))

